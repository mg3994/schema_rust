use heck::ToSnakeCase;
use crate::parser::ParsedVocabulary;

pub fn sanitize_rust_identifier(name: &str) -> String {
    let snake = name.to_snake_case();
    match snake.as_str() {
        "type" | "ref" | "use" | "move" | "match" | "fn" | "enum" | "struct" | "loop"
        | "while" | "for" | "if" | "else" | "let" | "mut" | "pub" | "crate" | "super"
        | "where" | "trait" | "impl" | "const" | "static" | "as" | "break" | "continue"
        | "return" | "async" | "await" | "dyn" | "abstract" | "override" | "unsized" => {
            format!("{}_value", snake)
        }
        _ => {
            if snake.chars().next().map_or(false, |c| c.is_ascii_digit()) {
                format!("n_{}", snake)
            } else {
                snake
            }
        }
    }
}

pub fn generate_vocabulary_code(vocab: &ParsedVocabulary) -> String {
    let mut out = String::new();

    out.push_str("// Auto-generated by schemaorg-codegen. DO NOT EDIT DIRECTLY.\n");
    out.push_str("use std::collections::{HashMap, HashSet};\n");
    out.push_str("use std::sync::OnceLock;\n\n");

    out.push_str("pub static KNOWN_TYPES_DATA: &[&str] = &[\n");
    for class_id in vocab.classes.keys() {
        out.push_str(&format!("    \"{}\",\n", class_id));
    }
    out.push_str("];\n\n");

    out.push_str("pub static PROPERTY_RANGES_DATA: &[(&str, &[&str])] = &[\n");
    for (prop_id, prop) in &vocab.properties {
        out.push_str(&format!("    (\"{}\", &[", prop_id));
        for (i, r) in prop.ranges.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            out.push_str(&format!("\"{}\"", r));
        }
        out.push_str("]),\n");
    }
    out.push_str("];\n\n");

    out.push_str("pub static KNOWN_TYPES: OnceLock<HashSet<&'static str>> = OnceLock::new();\n");
    out.push_str("pub static PROPERTY_RANGES: OnceLock<HashMap<&'static str, &'static [&'static str]>> = OnceLock::new();\n\n");

    out.push_str("pub fn init_vocabulary() {\n");
    out.push_str("    KNOWN_TYPES.get_or_init(|| {\n");
    out.push_str("        KNOWN_TYPES_DATA.iter().copied().collect()\n");
    out.push_str("    });\n");
    out.push_str("    PROPERTY_RANGES.get_or_init(|| {\n");
    out.push_str("        let mut map = HashMap::new();\n");
    out.push_str("        for (k, v) in PROPERTY_RANGES_DATA {\n");
    out.push_str("            map.insert(*k, *v);\n");
    out.push_str("        }\n");
    out.push_str("        map\n");
    out.push_str("    });\n");
    out.push_str("}\n\n");

    out.push_str("pub struct SchemaVocabulary;\n\n");
    out.push_str("impl SchemaVocabulary {\n");
    out.push_str("    pub fn is_known_type(type_name: &str) -> bool {\n");
    out.push_str("        init_vocabulary();\n");
    out.push_str("        let clean = type_name.trim_start_matches(\"schema:\").trim_start_matches(\"https://schema.org/\");\n");
    out.push_str("        KNOWN_TYPES.get().map_or(false, |set| set.contains(clean))\n");
    out.push_str("    }\n\n");

    out.push_str("    pub fn get_property_ranges(prop_name: &str) -> Option<&'static [&'static str]> {\n");
    out.push_str("        init_vocabulary();\n");
    out.push_str("        let clean = prop_name.trim_start_matches(\"schema:\").trim_start_matches(\"https://schema.org/\");\n");
    out.push_str("        PROPERTY_RANGES.get().and_then(|map| map.get(clean).copied())\n");
    out.push_str("    }\n\n");

    out.push_str("    pub fn get_unambiguous_range_type(prop_name: &str) -> Option<&'static str> {\n");
    out.push_str("        if let Some(ranges) = Self::get_property_ranges(prop_name) {\n");
    out.push_str("            if ranges.len() == 1 {\n");
    out.push_str("                let target = ranges[0];\n");
    out.push_str("                if target != \"Text\" && target != \"URL\" && target != \"Number\" && target != \"Boolean\" && target != \"Date\" && target != \"DateTime\" {\n");
    out.push_str("                    return Some(target);\n");
    out.push_str("                }\n");
    out.push_str("            }\n");
    out.push_str("        }\n");
    out.push_str("        None\n");
    out.push_str("    }\n");
    out.push_str("}\n");

    out
}
